"""Pydantic schemas for dynamic field mapping and autonomous form filling."""

from datetime import datetime, timezone
from typing import Optional, List, Literal
from pydantic import BaseModel, Field

FieldActionType = Literal[
    "fill_text",
    "select_option",
    "check_box",
    "select_radio",
    "upload_file",
    "click_element",
]


class FieldAction(BaseModel):
    """An individual atomic form interaction mapped from citizen profile or document vault."""

    action_type: FieldActionType = Field(..., description="Action category to perform")
    target_locator: str = Field(..., description="Playwright locator selector string")
    element_name: Optional[str] = Field(None, description="HTML name or id attribute")
    field_label: Optional[str] = Field(None, description="Resolved semantic label of the element")
    value: str = Field(..., description="Value to type, option value to select, or document path/identifier")
    source_attribute: Optional[str] = Field(None, description="Citizen profile field or document source")
    confidence: float = Field(0.95, ge=0.0, le=1.0, description="Mapping confidence score")
    reasoning: str = Field(..., description="Explanation of why this field maps to this profile attribute")


class FormFillPlan(BaseModel):
    """Structured sequence of form filling actions generated by dynamic mapping engine."""

    actions: List[FieldAction] = Field(default_factory=list, description="Ordered form population actions")
    unmapped_elements: List[str] = Field(
        default_factory=list, description="Interactive elements that have no matching profile attribute"
    )
    missing_mandatory_fields: List[str] = Field(
        default_factory=list, description="Required portal fields that cannot be populated from profile"
    )
    generated_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))


class ActionExecutionAudit(BaseModel):
    """Audit record capturing the outcome of an individual form action execution."""

    action_index: int = Field(..., description="Zero-based index of the action in the execution plan")
    action_type: FieldActionType = Field(..., description="Type of action executed")
    target_locator: str = Field(..., description="Playwright locator targeted")
    field_label: Optional[str] = Field(None, description="Field label")
    value: str = Field(..., description="Value passed to the action")
    status: Literal["success", "failed", "skipped"] = Field(..., description="Execution outcome")
    duration_ms: int = Field(0, description="Execution duration in milliseconds")
    error_message: Optional[str] = Field(None, description="Error detail if execution failed")


class FormExecutionResult(BaseModel):
    """Overall outcome of executing a FormFillPlan on a browser session."""

    session_id: str = Field(..., description="Associated browser session ID")
    total_actions: int = Field(..., description="Total actions planned")
    successful_actions: int = Field(..., description="Count of successfully executed actions")
    failed_actions: int = Field(0, description="Count of failed actions")
    action_results: List[ActionExecutionAudit] = Field(default_factory=list, description="Itemized audit trail")
    screenshot_base64: Optional[str] = Field(None, description="Post-fill browser screenshot buffer")
    completed_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
